#!/usr/bin/env python3
"""Generate inventory/manifest.sha256 over a Stargate SG-1 dump.

Usage: make-manifest.py DUMP_ROOT [-o OUT] [--check]

The dump is the extracted release tree (the directory that contains README.txt
and Stargate_SG-1_-_The_Alliance-2005-12-15/). Paths in the manifest are
relative to DUMP_ROOT and sorted, so the file is stable across machines.
No file contents are ever printed -- only hashes -- so the manifest is safe to
publish and is the anchor that lets every later task assume the same bytes.
"""
import argparse
import hashlib
import os
import sys


def sha256(path, chunk=1 << 20):
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for block in iter(lambda: fh.read(chunk), b""):
            h.update(block)
    return h.hexdigest()


def walk(root):
    out = []
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames.sort()
        for name in sorted(filenames):
            full = os.path.join(dirpath, name)
            if os.path.islink(full):
                continue
            out.append((os.path.relpath(full, root).replace(os.sep, "/"), full))
    out.sort()
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("dump_root")
    ap.add_argument("-o", "--output", default="inventory/manifest.sha256")
    ap.add_argument("--check", action="store_true",
                    help="verify against an existing manifest instead of writing")
    args = ap.parse_args()
    if not os.path.isdir(args.dump_root):
        sys.exit(f"not a directory: {args.dump_root}")

    files = walk(args.dump_root)
    if args.check:
        expected = {}
        with open(args.output, encoding="utf-8") as fh:
            for line in fh:
                line = line.rstrip("\n")
                if not line or line.startswith("#"):
                    continue
                digest, rel = line.split("  ", 1)
                expected[rel] = digest
        bad = missing = 0
        seen = set()
        for rel, full in files:
            seen.add(rel)
            got = sha256(full)
            seen_digest = expected.get(rel)
            if seen_digest is None:
                print(f"UNLISTED {rel}")
                bad += 1
            elif seen_digest != got:
                print(f"MISMATCH {rel}\n  manifest {seen_digest}\n  actual   {got}")
                bad += 1
        for rel in sorted(set(expected) - seen):
            print(f"MISSING  {rel}")
            missing += 1
        print(f"checked {len(files)} files: {bad} mismatched/unlisted, {missing} missing")
        sys.exit(1 if bad or missing else 0)

    os.makedirs(os.path.dirname(args.output) or ".", exist_ok=True)
    with open(args.output, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("# sha256  relative-path   (generated by tools/make-manifest.py)\n")
        for rel, full in files:
            fh.write(f"{sha256(full)}  {rel}\n")
    print(f"wrote {args.output}: {len(files)} files")


if __name__ == "__main__":
    main()
