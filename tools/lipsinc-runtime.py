#!/usr/bin/env python3
"""Locate the LIPSinc support module in the image and list what each of its functions says it does.

The lip-sync loader is native — `Engine.Actor`'s five `*LIPSincAnim` functions are natives with no serialised index
(`inventory/natives.csv`), so the code is in `default.xbe` and not in script. It is findable anyway: the module logs
through `[LIPSinc]:` strings, and the image still carries its own source path,
`\\alienbrainWork\\Stargate-sg1\\Game\\GameXBOX\\Engine\\Src\\LIPSincSupport.cpp` as an ASCII assert string.

    python3 tools/lipsinc-runtime.py --xbe DUMP/.../default.xbe -o inventory   # needs the image
    python3 tools/lipsinc-runtime.py --check                                   # dump-free, in `make ci`

The artifact is `inventory/lipsinc_runtime.csv`: one row per function that references a `[LIPSinc]:` log string, with
the string as its evidence — the same rule the naming convention uses (`docs/CONVENTIONS.md`: a name comes from a
string or assert site, and the evidence goes in the comment, not the claim). It does not *apply* names: the symbol
map is regenerated by a Ghidra run from `symbols/xbe_overrides.csv`, so the rename is its own commit.
"""
import argparse
import bisect
import csv
import os
import struct
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PREFIX = "[LIPSinc]: ".encode("utf-16-le")
COLUMNS = ["address", "size", "strings", "proposed_name"]


def utf16_at(data, off):
    out = []
    while off + 1 < len(data) and data[off:off + 2] != b"\x00\x00":
        out.append(data[off:off + 2])
        off += 2
    return b"".join(out).decode("utf-16-le", "replace")


def build(xbe_path, symbols):
    sys.path.insert(0, os.path.join(ROOT, "tools"))
    from xbe import Xbe                                        # noqa: PLC0415 - only when a dump exists

    xbe = Xbe(xbe_path)
    data = xbe.data
    sections = [(s.va, s.foff, s.fsize) for s in xbe.sections]

    def va_of(foff):
        for va, f, size in sections:
            if f <= foff < f + size:
                return va + (foff - f)
        return None

    def offset_of(va):
        for v, f, size in sections:
            if v <= va < v + size:
                return f + (va - v)
        return None

    # every `[LIPSinc]:` string, in one pass over the image
    strings, i = {}, 0
    while True:
        i = data.find(PREFIX, i)
        if i < 0:
            break
        va = va_of(i)
        if va is not None:
            strings[va] = utf16_at(data, i)
        i += 1

    funcs = {int(r["address"], 16): int(r["size"]) for r in csv.DictReader(open(symbols))}
    starts = sorted(funcs)

    def owner(va):
        k = bisect.bisect_right(starts, va) - 1
        if k < 0:
            return None
        s = starts[k]
        return (s, funcs[s]) if s <= va < s + funcs[s] else None

    # a log call is `push <string va>`; scan for that and attribute the site to its function
    found = {}
    for off in range(0, len(data) - 5):
        if data[off] != 0x68:
            continue
        target = struct.unpack_from("<I", data, off + 1)[0]
        if target not in strings:
            continue
        va = va_of(off)
        if va is None:
            continue
        hit = owner(va)
        if hit:
            found.setdefault(hit, set()).add(target)

    rows = []
    for (addr, size), targets in sorted(found.items()):
        texts = sorted(strings[t][len("[LIPSinc]: "):] for t in targets)
        rows.append({"address": "0x%08x" % addr, "size": size, "strings": " | ".join(texts),
                     "proposed_name": propose(texts)})
    return rows, len(strings)


def propose(texts):
    """A name only where the module names itself; otherwise empty rather than a guess."""
    joined = " ".join(texts)
    for token in ("LIPSincInitLevel", "LIPSincInitGame", "LIPSincShutdownLevel", "LIPSincShutdownGame",
                  "LIPSincShutdownEditor", "LIPSincInitEditor"):
        if token in joined:
            return token
    if "LoadLIPSincDBFromDisk" in joined:
        return "LIPSincLoadDBFromDisk"
    if "Read Track" in joined and "Couldn't load file" in joined:
        return "LIPSincReadAnimFile"
    if "LIPSinc bone linkup failed" in joined and "obsolete .LBP" in joined:
        return "LIPSincReadControllerFile"
    if "PlayLIPSincAnim for" in joined:
        return "LIPSincPlayAnim"
    if "Linking Bones for" in joined:
        return "LIPSincLinkBones"
    if "Searching for .lad files" in joined:
        return "LIPSincSearchAnimFiles"
    return ""


def check(path):
    rows = list(csv.DictReader(open(path)))
    problems = []
    if not rows:
        problems.append("no rows")
    for r in rows:
        if sorted(r) != sorted(COLUMNS):
            problems.append("columns")
            break
        if not r["strings"].strip():
            problems.append("%s: no evidence string" % r["address"])
        if r["proposed_name"] and not r["proposed_name"].startswith("LIPSinc"):
            problems.append("%s: proposed name %r" % (r["address"], r["proposed_name"]))
    if problems:
        print("FAIL lipsinc-runtime: " + "; ".join(problems[:5]))
        return 1
    named = sum(1 for r in rows if r["proposed_name"])
    print("ok   lipsinc-runtime: %d functions, %d with a self-evident name" % (len(rows), named))
    return 0


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--xbe")
    ap.add_argument("--symbols", default=os.path.join(ROOT, "symbols", "xbox_functions.csv"))
    ap.add_argument("-o", "--out", default=os.path.join(ROOT, "inventory"))
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    path = os.path.join(args.out, "lipsinc_runtime.csv")
    if args.check:
        return check(path)
    if not args.xbe:
        ap.error("--xbe is required unless --check")
    rows, n = build(args.xbe, args.symbols)
    os.makedirs(args.out, exist_ok=True)
    with open(path, "w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=COLUMNS, lineterminator="\n")
        w.writeheader()
        for r in rows:
            w.writerow(r)
    print("%d [LIPSinc] strings, %d functions; wrote %s" % (n, len(rows), path))
    for r in rows:
        print("  %s %5d  %-26s %s" % (r["address"], r["size"], r["proposed_name"] or "-", r["strings"][:60]))
    return 0


if __name__ == "__main__":
    sys.exit(main())
