#!/usr/bin/env python3
"""Index the committed measurement artifacts: what each file is, and what regenerates it.

Not to be confused with `docs/INVENTORY.md`, which is `tools/gen-inventory-doc.py`'s package-by-package census
of the dump. This page is about the repository's own CSVs.

Every number in this repository lives in a CSV, and the rule is that the document which quotes a number names the
command that produces it. This tool makes that rule checkable: it lists each committed artifact with its row and
column count, and resolves which `make` target regenerates it — by finding the file name in the Makefile, or in
the tool that writes it and then the target that runs that tool.

    python3 tools/inventory-index.py            # writes docs/ARTIFACTS.md
    python3 tools/inventory-index.py --check    # fails if the committed page is stale

An artifact that resolves to *neither* a target nor a tool is reported as an orphan. That is the useful part of
the index: a CSV nobody regenerates is a CSV that will drift.
"""
import argparse
import csv
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ARTIFACT_DIRS = ("inventory", "symbols")


def artifacts():
    out = []
    for d in ARTIFACT_DIRS:
        full = os.path.join(ROOT, d)
        if not os.path.isdir(full):
            continue
        for f in sorted(os.listdir(full)):
            if f.endswith(".csv"):
                out.append(os.path.join(d, f))
    return out


def describe(path):
    with open(os.path.join(ROOT, path), newline="") as fh:
        r = csv.reader(fh)
        try:
            header = next(r)
        except StopIteration:
            return 0, []
        rows = sum(1 for _ in r)
    return rows, header


def targets():
    """Makefile target -> recipe text."""
    out = {}
    cur = None
    for line in open(os.path.join(ROOT, "Makefile")):
        if line.startswith("\t"):
            if cur:
                out[cur] += line
            continue
        m = re.match(r"^([A-Za-z0-9_.-]+):", line)
        if m and not line.startswith(".PHONY"):
            cur = m.group(1)
            out.setdefault(cur, "")
        elif line.strip() and not line.startswith("#"):
            cur = None
    return out


def tools():
    """Tool file name -> its source text, for the Python tools and the Ghidra scripts alike.

    The Ghidra scripts matter: `xbe_block_seeds.csv` is written by `SeedGaps.java`, which
    `tools/ghidra/run-analysis.sh` runs, so the artifact *is* regenerated by `make ghidra` even though the file
    name appears in neither the Makefile nor a Python tool.
    """
    out = {}
    for dirpath, _dirs, files in os.walk(os.path.join(ROOT, "tools")):
        for f in sorted(files):
            if f.endswith((".py", ".java", ".sh", ".cs")):
                try:
                    out[f] = open(os.path.join(dirpath, f), encoding="utf-8", errors="replace").read()
                except OSError:
                    continue
    return out


def resolve(path, mk, tl):
    """(kind, owner) for an artifact: a make target, a tool that a target runs, or nothing."""
    base = os.path.basename(path)
    stem = base[:-4] if base.endswith(".csv") else base
    for target, recipe in mk.items():
        if base in recipe or stem in recipe:
            return "target", target
    writers = [name for name, src in tl.items() if base in src or stem in src]

    def credits(w, recipe):
        """Does `recipe` run the tool `w`? A .cs file is run through Sg1Tool's verb, not by name."""
        if w in recipe:
            return True
        verb = dotnet_verb(w)
        # `Sg1Tool ... -- inventory --dump` or `$(TOOL) maps --dump`: the verb opens a command and is
        # followed by its first option. Matching the bare word would credit every recipe writing `-o inventory`.
        return bool(verb) and bool(re.search(r"(?:^|\s)" + re.escape(verb) + r"\s+--[a-z]", recipe, re.M))

    for w in writers:
        for target, recipe in mk.items():
            if credits(w, recipe):
                return "target", target
    if writers:
        return "tool", writers[0] + " (no target runs it)"
    return "orphan", ""


def dotnet_verb(writer):
    """`InventoryCommand.cs` -> `inventory`: the Sg1Tool verb that class implements."""
    stem = writer[:-3] if writer.endswith(".cs") else ""
    if stem.endswith("Command"):
        return stem[: -len("Command")].lower()
    return ""


def page(rows):
    lines = ["# Artifact index", "",
             "_Generated by `tools/inventory-index.py` from the committed files — do not edit._", "",
             "Every measurement this project makes is a committed CSV. This is the map: what each one holds, and "
             "what regenerates it. An artifact with no target is a gap, not a detail — nothing rebuilds it, so it "
             "drifts silently.", "",
             "| artifact | rows | columns | regenerated by |", "|---|---:|---:|---|"]
    for path, nrows, header, kind, owner in rows:
        how = ("`make %s`" % owner) if kind == "target" else ("**%s**" % owner if owner else "**no generator**")
        lines.append("| `%s` | %d | %d | %s |" % (path, nrows, len(header), how))
    orphans = [r for r in rows if r[3] == "orphan"]
    tot = sum(r[1] for r in rows)
    lines += ["", "%d artifacts, %d rows in total. %d with no generator."
              % (len(rows), tot, len(orphans)), ""]
    if orphans:
        lines += ["## Not regenerated by any target", ""]
        for path, nrows, _h, _k, _o in orphans:
            lines.append("* `%s` (%d rows)" % (path, nrows))
        lines.append("")
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="compare against the committed page instead of writing")
    args = ap.parse_args()

    mk, tl = targets(), tools()
    rows = []
    for path in artifacts():
        nrows, header = describe(path)
        kind, owner = resolve(path, mk, tl)
        rows.append((path, nrows, header, kind, owner))

    text = page(rows)
    target = os.path.join(ROOT, "docs", "ARTIFACTS.md")
    if args.check:
        try:
            current = open(target, encoding="utf-8").read()
        except FileNotFoundError:
            print("FAIL docs/ARTIFACTS.md: missing (run tools/inventory-index.py)")
            return 1
        if current != text:
            print("FAIL docs/ARTIFACTS.md: stale (run tools/inventory-index.py)")
            return 1
        print("ok   inventory-index: docs/ARTIFACTS.md (%d artifacts)" % len(rows))
        return 0
    with open(target, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    print("wrote docs/ARTIFACTS.md: %d artifacts, %d rows"
          % (len(rows), sum(r[1] for r in rows)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
