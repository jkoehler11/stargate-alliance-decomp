#!/usr/bin/env python3
"""Render docs/INVENTORY.md from the generated CSVs.

The doc is generated so the numbers can never drift from the CSVs that CI regenerates; the prose
around them is fixed. Run after `make inventory`.
"""
import csv
import os
from collections import Counter, defaultdict

INV = "inventory"
OUT = "docs/INVENTORY.md"


def rows(name):
    with open(os.path.join(INV, name), newline="", encoding="utf-8") as fh:
        return list(csv.DictReader(fh))


def main():
    pkgs = rows("packages.csv")
    classes = rows("classes.csv")
    natives = rows("natives.csv")
    modules = rows("xbe_module_summary.csv")
    dirs = rows("directories.csv")
    exts = rows("extensions.csv")

    total_bytes = sum(int(d["bytes"]) for d in dirs)
    total_files = sum(int(d["files"]) for d in dirs)
    pkg_classes = Counter(c["package"] for c in classes)
    natives_by_pkg = Counter(n["package"] for n in natives)
    tokens = Counter(int(n["native_token"]) for n in natives)
    collisions = sum(1 for v in tokens.values() if v > 1)

    out = []
    w = out.append
    w("# Inventory")
    w("")
    w("Generated by `tools/gen-inventory-doc.py` from the CSVs in `inventory/`. Do not edit by hand:")
    w("regenerate with `make inventory` and this script (deterministic, so a diff means the dump")
    w("or the tooling changed).")
    w("")
    w("## Dump")
    w("")
    w(f"- {total_files:,} files, {total_bytes:,} bytes ({total_bytes / 2**30:.2f} GiB)")
    w(f"- {len(exts)} extensions, {len(dirs)} top-level directory groups")
    w(f"- {len(pkgs)} UnrealScript packages, "
      f"{len([m for m in modules if m['module'] != '?'])} native modules in `default.xbe`")
    w("")
    w("## Packages")
    w("")
    w("| package | version | licensee | exports | classes | functions | native fns | states |")
    w("|---|---|---|---|---|---|---|---|")
    for p in pkgs:
        w(f"| `{p['package']}.u` | {p['version']} | {p['licensee_version']} | {int(p['export_count']):,} "
          f"| {p['class_exports']} | {int(p['function_exports']):,} | {p['native_function_exports']} "
          f"| {p['state_exports']} |")
    w("")
    w(f"Totals: **{len(classes):,} classes**, "
      f"**{sum(int(p['function_exports']) for p in pkgs):,} functions**, "
      f"**{len(natives):,} native functions**, "
      f"**{sum(int(p['state_exports']) for p in pkgs):,} states**.")
    w("")
    w("Every package reports UELib build `SG1_TA` (version 130 / licensee 4, `UPreview.u` at 128) — the")
    w("per-game profile UELib ships for this title, so the bytecode token map is a known quantity")
    w("rather than something reconstructed here.")
    w("")
    w("## Natives")
    w("")
    w("`native()` declarations carry a global token: the engine dispatches through one table, so tokens")
    w(f"must be unique. {len(natives):,} declarations produced {len(tokens):,} distinct tokens and "
      f"{collisions} collision(s) — i.e. a single index space for every package.")
    w("")
    w("Having one index space is not the same as having addresses: `GNatives` is populated at runtime and")
    w("the image stores no bytes for it, so naming a slot needs the table read from a running build")
    w("(`docs/NATIVE_VM.md`, PLAN 4.3/4.4).")
    w("")
    w("| package | native functions |")
    w("|---|---|")
    for pkg, count in natives_by_pkg.most_common():
        w(f"| `{pkg}.u` | {count} |")
    w("")
    w("## Native modules (`default.xbe`)")
    w("")
    w("Derived from `__FILE__` assert paths plus code xrefs to each path string (`tools/xbe.py asserts`).")
    w("")
    w("| module | translation units | assert xrefs | headers |")
    w("|---|---|---|---|")
    for m in modules:
        if m["module"] == "?":
            continue
        w(f"| `{m['module']}` | {m['src_files']} | {m['src_refs']} | {m['inc_files']} |")
    w("")
    w("## Maps and content")
    w("")
    try:
        maps = rows("maps.csv")
        chapters = rows("chapters.csv")
        w(f"- {len(maps)} `.unr` maps, {sum(int(m['actor_exports']) for m in maps):,} placed actors")
        if chapters:
            present = sum(1 for c in chapters if c["present_on_disk"] == "true")
            w(f"- {len(chapters)} chapters defined in `ChapterList.ini`; {present} reference a shipped map")
        w("- per-map census: [CONTENT_CENSUS.md](CONTENT_CENSUS.md)")
    except FileNotFoundError:
        w("- map census not generated yet (`make inventory`)")
    w("")
    w("## Files by directory")
    w("")
    w("| path | files | bytes |")
    w("|---|---|---|")
    for d in dirs:
        w(f"| `{d['path']}` | {int(d['files']):,} | {int(d['bytes']):,} |")
    w("")
    w("## Reading this table")
    w("")
    w("- `classes.csv` counts classes this package *defines* (exports), not classes it references.")
    w("- `is_native` is true when the class owns `native` functions: UE2 has no plain class-level")
    w("  `native` bit in `ClassFlags`, so ownership is the only mechanical definition. `native_only`")
    w("  records the separate `CLASS_NativeOnly` bit.")
    w("- A class count lower than the leaked 2006 source is expected: this build is six months older")
    w("  and the leak is an oracle, not ground truth (`PLAN.md` risk 5).")
    w("")
    with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(out))
    print(f"wrote {OUT}: {len(out)} lines")


if __name__ == "__main__":
    main()
