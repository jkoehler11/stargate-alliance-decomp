#!/usr/bin/env python3
"""Rank the decompiler's unresolved bytecode tokens and write docs/DECOMPILER_GAPS.md.

UELib renders tokens it cannot name for this build as `__NFUN_<n>__`. Each one is a place where the
reconstructed script is structurally right but semantically unreadable, so this list is the work
queue for PLAN 3.5 -- ordered by how much of the tree each token would fix.

Usage: token-gaps.py [SRC_DIR]   (default $WORK/UnrealScript)
"""
import collections
import glob
import os
import re
import sys

TOKEN = re.compile(r"__NFUN_(\d+)__")
OUT = "docs/DECOMPILER_GAPS.md"


def main():
    src = sys.argv[1] if len(sys.argv) > 1 else os.environ.get(
        "WORK", os.path.expanduser("~/sg1/work")) + "/UnrealScript"
    files = sorted(glob.glob(os.path.join(src, "*", "*.uc")))
    if not files:
        sys.exit(f"no .uc files under {src} -- run 'make decompile' first")
    token = collections.Counter()
    per_pkg = collections.Counter()
    classes_affected = collections.Counter()
    sites = 0
    for path in files:
        text = open(path, encoding="utf-8", errors="replace").read()
        found = TOKEN.findall(text)
        if not found:
            continue
        sites += len(found)
        pkg = os.path.basename(os.path.dirname(path))
        per_pkg[pkg] += len(found)
        for name in set(found):
            classes_affected[int(name)] += 1
        for n in found:
            token[int(n)] += 1

    out = []
    w = out.append
    w("# Decompiler gaps (unresolved bytecode tokens)")
    w("")
    w("Generated by `tools/token-gaps.py` after `make decompile`. Every `__NFUN_<n>__` in the")
    w("reconstructed tree is a token UELib cannot name for build `SG1_TA`; the script is")
    w("structurally reconstructed but that expression or call is unreadable until the token map")
    w("is extended. Work queue for `PLAN.md` 3.5 — fix the most frequent tokens first.")
    w("")
    w(f"- {len(files):,} classes reconstructed, {sites:,} unresolved sites, "
      f"{len(token)} distinct tokens")
    if token:
        w(f"- top token `__NFUN_{token.most_common(1)[0][0]}__` alone accounts for "
          f"{token.most_common(1)[0][1]:,} sites")
    else:
        w("- no unresolved sites: every native call in the tree resolved to a name")
    w("")
    w("## Tokens by frequency")
    w("")
    if not token:
        w("Nothing to report. The tree is fully readable with respect to native calls; keep this file")
        w("as the regression check — a non-empty table means a table-building change went wrong.")
    w("| token | sites | classes affected |")
    w("|---|---|---|")
    for n, count in token.most_common(25):
        w(f"| `__NFUN_{n}__` | {count:,} | {classes_affected[n]:,} |")
    w("")
    w("## Sites by package")
    w("")
    w("| package | unresolved sites |")
    w("|---|---|")
    for pkg, count in per_pkg.most_common():
        w(f"| `{pkg}` | {count:,} |")
    w("")
    w("## How to close these")
    w("")
    w("1. Classify each token: bytecode operator (below the native index range) vs a `native()`")
    w("   entry that has no name because the function lives in a class this build does not ship.")
    w("2. For operators, extend the UE2.5 token map in UELib (per-build override) with the operator")
    w("   names the grammar expects, then re-run `make decompile` and diff this report.")
    w("3. For natives, cross-reference `inventory/natives.csv`: a token that collides with a known")
    w("   `native()` index in the same package is a nameable call, not an operator.")
    w("4. Track the trend, not the absolute number: the goal is monotone decrease per token fixed.")
    w("")
    with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(out))
    print(f"{sites:,} sites / {len(token)} tokens -> {OUT}")


if __name__ == "__main__":
    main()
