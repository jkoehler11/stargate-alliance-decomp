#!/usr/bin/env python3
"""Render the project's state as a progress table, from committed artifacts only.

The table in `README.md` and the page in `docs/STATUS.md` are generated: every percentage comes from a
committed CSV or the symbol map, and each row names its source. Nothing here is estimated -- a metric
that has not been measured prints as `--`, which is the honest state of the compile and asset layers.

    python3 tools/status.py            # rewrites docs/STATUS.md and the README block
    python3 tools/status.py --check    # exit 1 if either is stale (what `make ci` runs)

Bars are `filled/total` over 24 cells; the marker is by band, so a reader can see the shape before
reading the number: green >= 90, yellow >= 50, orange >= 10, red < 10, white = not measured.
"""
import argparse
import csv
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CELLS = 24
BEGIN = "<!-- status:begin (generated by tools/status.py) -->"
END = "<!-- status:end -->"


def repo(*p):
    return os.path.join(ROOT, *p)


def rows_of(path):
    with open(repo(path), newline="") as f:
        return list(csv.DictReader(f))


def count_manifest(suffix, must_contain=None):
    n = 0
    with open(repo("inventory/manifest.sha256")) as f:
        for line in f:
            if line.startswith("#") or not line.strip():
                continue
            path = line.split(None, 1)[1].strip()
            if path.lower().endswith(suffix) and (must_contain is None or must_contain in path):
                n += 1
    return n


def pct(have, total):
    return 100.0 * have / total if total else 0.0


def bar(have, total):
    if total == 0 or have is None:
        return "`" + "\u2591" * CELLS + "`"
    filled = int(round(CELLS * have / total))
    return "`" + "\u2588" * filled + "\u2591" * (CELLS - filled) + "`"


def mark(have, total):
    if have is None or total == 0:
        return "\u2b1c"
    p = pct(have, total)
    if p >= 90:
        return "\U0001f7e9"
    if p >= 50:
        return "\U0001f7e8"
    if p >= 10:
        return "\U0001f7e7"
    return "\U0001f7e5"


def collect():
    """(layer, metric, have, total, source). have None means 'not measured'."""
    out = []

    # Script track ----------------------------------------------------------
    cov = rows_of("inventory/decompile_coverage.csv")
    ok = [r for r in cov if r["status"] == "ok"]
    out.append(("Script", "classes reconstructed (L0)", len(ok), len(cov),
                "inventory/decompile_coverage.csv"))
    pkgs = rows_of("inventory/packages.csv")
    out.append(("Script", "shipped packages parsed", len(pkgs), count_manifest(".u"),
                "inventory/packages.csv vs inventory/manifest.sha256"))
    od = rows_of("inventory/oracle_diff.csv")
    oracle_total = sum(1 for r in od if r["bucket"] != "build-only")
    oracle_match = sum(1 for r in od if r["bucket"] == "matched")
    out.append(("Script", "classes agreeing with the 2006 source", oracle_match, oracle_total,
                "inventory/oracle_diff.csv (bucket=matched / all oracle classes)"))
    out.append(("Script", "classes compiling clean (L1)", None, None, "PLAN 3.6 has not started (inputs: docs/COMPILE.md)"))
    cd_rows = rows_of("inventory/class_defaults_coverage.csv")
    cd_total = sum(int(r["classes"]) for r in cd_rows)
    cd_read = sum(int(r["fully_declared"]) for r in cd_rows)
    out.append(("Script", "class defaults decoded", cd_read, cd_total,
                "inventory/class_defaults_coverage.csv (fully_declared / classes)"))
    em_rows = rows_of("inventory/class_defaults_emit.csv")
    em_props = sum(int(r["properties"]) for r in em_rows)
    em_done = sum(int(r["rendered"]) for r in em_rows)
    out.append(("Script", "default properties rendered", em_done, em_props,
                "inventory/class_defaults_emit.csv (rendered / properties in fully-declared blocks)"))

    # Native track ---------------------------------------------------------
    funcs = rows_of("symbols/xbox_functions.csv")
    named = [r for r in funcs if not r["name"].startswith("FUN_")]
    out.append(("Native", "functions carrying a name", len(named), len(funcs),
                "symbols/xbox_functions.csv (name not FUN_*)"))
    by_module = rows_of("inventory/xbe_functions_by_module.csv")
    attributed = sum(int(r["functions"]) for r in by_module if r["module"] != "(unnamed)")
    out.append(("Native", "functions attributed to a module", attributed, len(funcs),
                "inventory/xbe_functions_by_module.csv (all rows except '(unnamed)')"))
    tables = rows_of("inventory/xbe_class_table_names.csv")
    named_tables = [r for r in tables if r["class"]]
    out.append(("Native", "class tables named", len(named_tables), len(tables),
                "inventory/xbe_class_table_names.csv"))
    props = rows_of("inventory/property_classes.csv")
    out.append(("Native", "property classes measured", len(props), 15,
                "inventory/property_classes.csv (15 = base + 14 subclasses)"))

    # Content track --------------------------------------------------------
    maps = rows_of("inventory/maps.csv")
    out.append(("Content", "maps parsed", len(maps), count_manifest(".unr"),
                "inventory/maps.csv vs manifest"))
    speech = rows_of("inventory/speech_index.csv")
    out.append(("Content", "speech WAVs indexed", len(speech),
                count_manifest(".wav", "/Speech/"), "inventory/speech_index.csv vs manifest"))
    music = rows_of("inventory/music_index.csv")
    out.append(("Content", "music WAVs indexed", sum(int(r["files"]) for r in music),
                count_manifest(".wav", "/Music/"), "inventory/music_index.csv vs manifest"))

    # Deliverables ---------------------------------------------------------
    relayout = rows_of("inventory/package_relayout.csv")
    resizes_tested = sum(int(r["exports_tested"]) for r in relayout)
    resizes_passed = sum(int(r["passed"]) for r in relayout)
    out.append(("Deliverables", "payload resizes that round-trip (6.1 writer)", resizes_passed, resizes_tested,
                "inventory/package_relayout.csv (passed / exports_tested)"))
    out.append(("Deliverables", "assets exported (5.1)", None, None, "PLAN 5.1 has not started"))
    out.append(("Deliverables", "bootable rebuild (6.x)", None, None, "PLAN 6.1 has not started"))
    return out


def render(rows):
    head = ("| Layer | Measure | Have | Of | Progress | |\n|---|---|---:|---:|---|:--:|\n")
    body = ""
    for layer, metric, have, total, _src in rows:
        if have is None:
            body += "| %s | %s | -- | -- | %s | %s |\n" % (
                layer, metric, bar(None, 0), mark(None, 0))
        else:
            body += "| %s | %s | %s | %s | %s %.2f%% | %s |\n" % (
                layer, metric, f"{have:,}", f"{total:,}", bar(have, total), pct(have, total),
                mark(have, total))
    return head + body


def headline(rows):
    g = {(l, m): (h, t) for l, m, h, t, _ in rows}
    class_h, class_t = g[("Script", "classes reconstructed (L0)")]
    fn_h, fn_t = g[("Native", "functions carrying a name")]
    return ("**%.2f%% of the script tree is reconstructed (L0) and %.2f%% of the native functions "
            "carry a name.**" % (pct(class_h, class_t), pct(fn_h, fn_t)))


def sources(rows):
    seen = []
    for layer, metric, have, total, src in rows:
        line = "| %s | %s | %s |" % (layer, metric, src)
        if line not in seen:
            seen.append(line)
    return ("| Layer | Measure | Source |\n|---|---|---|\n" + "\n".join(seen) + "\n")


def badge(rows):
    g = {(l, m): (h, t) for l, m, h, t, _ in rows}
    s_h, s_t = g[("Script", "classes reconstructed (L0)")]
    n_h, n_t = g[("Native", "functions carrying a name")]
    s, n = pct(s_h, s_t), pct(n_h, n_t)
    colour = lambda p: "3fb950" if p >= 90 else ("d29922" if p >= 50 else ("db6d28" if p >= 10 else "da3633"))
    return ('  <img alt="Script: %.2f%% reconstructed" src="https://img.shields.io/badge/script%%20L0-%.2f%%25-%s">\n'
            '  <img alt="Native: %.2f%% named" src="https://img.shields.io/badge/native%%20symbols-%.2f%%25-%s">'
            % (s, s, colour(s), n, n, colour(n)))


def write(path, text):
    full = repo(path)
    with open(full, "w") as f:
        f.write(text)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()

    rows = collect()
    table = render(rows)
    page = (
        "# Project status\n\n"
        "_Generated by `tools/status.py` from committed artifacts — do not edit._\n\n"
        + headline(rows) + "\n\n" + table + "\n"
        "| | |\n|---|---|\n"
        "| \U0001f7e9 \u2265 90% | \U0001f7e8 \u2265 50% | \U0001f7e7 \u2265 10% | \U0001f7e5 < 10% | \u2b1c not measured |\n\n"
        "A row that has not been measured says `--` rather than `0.00%`: the compile loop (PLAN 3.6), the\n"
        "asset export (5.1) and the bootable rebuild (6.x) have not started, so the honest number does not\n"
        "exist yet. That is different from a layer that was measured and scored badly.\n\n"
        "## Where each number comes from\n\n" + sources(rows) + "\n"
        "## Reading the native rows\n\n"
        "`functions carrying a name` counts every function whose name is not `FUN_*`: assert-derived file\n"
        "attribution, the runtime `GNatives` names, class-registration overrides, and the `Vtbl_*` tables are\n"
        "not functions and are excluded. Naming the remaining `FUN_*` set needs the signature databases that\n"
        "this repository may not carry (`docs/UNKNOWNS.md` U9), so the ceiling without them is not 100%.\n"
    )

    readme_path = repo("README.md")
    readme = open(readme_path).read()
    block = BEGIN + "\n" + headline(rows) + "\n\n" + table + "\n" + END
    if BEGIN in readme and END in readme:
        start = readme.index(BEGIN)
        stop = readme.index(END) + len(END)
        new_readme = readme[:start] + block + readme[stop:]
    else:
        new_readme = readme
    badge_line = badge(rows)
    if 'alt="Script:' in new_readme or True:
        import re
        new_readme = re.sub(r'(?m)^  <img alt="Status: [^\n]*\n', badge_line + "\n", new_readme)

    page_path = repo("docs/STATUS.md")
    old_page = open(page_path).read() if os.path.isfile(page_path) else None
    old_readme = readme

    if args.check:
        bad = []
        if old_page != page:
            bad.append("docs/STATUS.md")
        if old_readme != new_readme:
            bad.append("README.md status block")
        if bad:
            print("stale: " + ", ".join(bad) + " -- run python3 tools/status.py")
            return 1
        print("ok   status-table: docs/STATUS.md and README.md")
        return 0

    write("docs/STATUS.md", page)
    open(readme_path, "w").write(new_readme)
    print(headline(rows).replace("**", ""))
    print("wrote docs/STATUS.md and the README status block")


if __name__ == "__main__":
    sys.exit(main())
