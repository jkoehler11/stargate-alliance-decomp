#!/usr/bin/env python3
"""Emit the symbol map: a text map plus a symbol file a debugger can load.

The native track's output is a symbol map (`symbols/xbox_functions.csv`) whose names come from the
build itself: the assert each function references, the runtime native table, the class registrations.
This turns it into two artifacts a person or a tool can use against the original XBE:

  symbols/xbox.map     address, name, size, module -- greppable, and the form a map file is read in
  symbols/xbox.sym.s   one absolute global symbol per name, assembled into an object file that gdb
                       or any ELF reader will load, so `x 1i Address` and `break *Name` work against
                       a running build in the emulator

    python3 tools/make-symbols.py -o symbols
    as --32 -o symbols/xbox.sym.o symbols/xbox.sym.s        # or: make symbols
    gdb -batch -ex "symbol-file symbols/xbox.sym.o" -ex "info address FUN_0004bf20"

Names are the build's; nothing is invented here. Symbols whose names would not survive assembly are
sanitised in the .s only -- the .map always carries the exact name -- and collisions are counted, not
silently renamed.
"""
import argparse
import csv
import os
import re

SAFE = re.compile(r"[^A-Za-z0-9_.$]")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--symbols", default="symbols/xbox_functions.csv")
    ap.add_argument("--tables", default="inventory/xbe_class_table_names.csv")
    ap.add_argument("--xbe", help="validate every address against this image's sections")
    ap.add_argument("-o", "--out", default="symbols")
    args = ap.parse_args()

    entries = {}
    with open(args.symbols) as f:
        for row in csv.DictReader(f):
            entries[int(row["address"], 16)] = (row["name"], int(row["size"]), row.get("module") or "")

    # The class tables are the vtables objects are constructed with (docs/NATIVE_CLASSES.md): they
    # are not functions, so they are not in the function map, and a debugger needs them by name.
    added = 0
    if args.tables and os.path.isfile(args.tables):
        with open(args.tables) as f:
            for row in csv.DictReader(f):
                if not row["class"]:
                    continue
                va = int(row["table_va"], 16)
                if va in entries:
                    continue
                entries[va] = ("Vtbl_" + row["class"], int(row.get("object_size") or 0), "class table")
                added += 1

    # A map that puts a symbol outside the image is worse than no map, so it is checked against the
    # section table when the image is at hand (the acceptance criterion in PLAN 4.10).
    outside = []
    if args.xbe:
        import sys
        sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
        from xbe import Xbe
        xbe = Xbe(args.xbe)
        for va in entries:
            if not any(sec.va <= va < sec.va + sec.vsize for sec in xbe.sections):
                outside.append(va)

    os.makedirs(args.out, exist_ok=True)
    safe = {}
    clashes = 0
    with open(os.path.join(args.out, "xbox.map"), "w") as m:
        m.write("# Stargate SG-1: The Alliance (Xbox, 2005-12-15) -- symbol map\n")
        m.write("# generated by tools/make-symbols.py from symbols/xbox_functions.csv;\n")
        m.write("# address name size module. Nothing here is a guess: every name comes from the build\n")
        m.write("# (the assert it references, the runtime native table, or its class registration).\n")
        for va in sorted(entries):
            name, size, module = entries[va]
            m.write("0x%08x %-42s %6d %s\n" % (va, name, size, module))
            sym = SAFE.sub("_", name)
            if not sym or sym[0].isdigit():
                sym = "_" + sym
            if sym in safe and safe[sym] != va:
                clashes += 1
                sym = "%s_%08x" % (sym, va)
            safe[sym] = va
    with open(os.path.join(args.out, "xbox.sym.s"), "w") as s:
        s.write("# generated by tools/make-symbols.py -- one absolute global per name.\n")
        s.write("# assemble with: as --32 -o xbox.sym.o xbox.sym.s\n")
        for sym in sorted(safe):
            s.write(".globl %s\n.set %s, 0x%08x\n" % (sym, sym, safe[sym]))
    print("%d symbols (%d class tables added), %d name collisions sanitised"
          % (len(safe), added, clashes))
    if args.xbe:
        print("addresses inside the image: %d of %d, outside: %d"
              % (len(entries) - len(outside), len(entries), len(outside)))
        if outside:
            raise SystemExit("symbols outside the image: %s" % ", ".join("0x%08x" % v for v in outside[:8]))
    print("wrote %s/xbox.map and %s/xbox.sym.s" % (args.out, args.out))


if __name__ == "__main__":
    main()
