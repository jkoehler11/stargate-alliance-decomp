#!/usr/bin/env python3
"""Summarise the Ghidra symbol map into a per-module function table plus docs/NATIVE.md.

Input is symbols/xbox_functions.csv as written by tools/ghidra/ghidra_scripts/XbePost.java:
address,name,size,module -- where names come from the assert string the function references
(`Engine_UnObjBas`) or stay Ghidra-generated (`FUN_0014a2c0`).

Usage: native-summary.py [-o inventory]
"""
import argparse
import csv
import os
import re
from collections import Counter, defaultdict

FUN = re.compile(r"^(FUN|sub|thunk_FUN|LAB)_([0-9a-fA-F]+)$")
NATIVE_SLOT = re.compile(r"^Native_\d+$")
# The 12 modules that assert somewhere in this binary; a name is only attributed to a module when
# its prefix is one of these, otherwise an MSVC-mangled symbol would invent a module of its own.
KNOWN_MODULES = {"Engine", "Core", "IpDrv", "Gui", "D3DDrv", "XboxDrv", "XboxAudio", "XboxLive",
                 "Gameplay", "Fire", "stargategame", "stargatevehicles"}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--symbols", default="symbols/xbox_functions.csv")
    ap.add_argument("--overrides", default="symbols/xbe_overrides.csv",
                    help="evidence-based names; their module attribution joins the assert counts")
    ap.add_argument("-o", "--out", default="inventory")
    args = ap.parse_args()
    if not os.path.isfile(args.symbols):
        raise SystemExit(f"{args.symbols} not found -- run `make ghidra` first")

    # A function renamed by an evidence override (symbols/xbe_overrides.csv) keeps its module
    # attribution from the override, not from the assert-derived prefix it no longer carries.
    overrides = {}
    if args.overrides and os.path.isfile(args.overrides):
        with open(args.overrides, newline="", encoding="utf-8") as fh:
            for row in csv.DictReader(fh):
                overrides[row["address"].lower()] = row

    rows = []
    with open(args.symbols, newline="", encoding="utf-8") as fh:
        for row in csv.DictReader(fh):
            name = row["name"]
            unknown = bool(FUN.match(name))
            prefix = name.split("_", 1)[0]
            module = prefix if (not unknown and prefix in KNOWN_MODULES) else ""
            override = overrides.get(row["address"].lower())
            if override and override["module"] in KNOWN_MODULES:
                module = override["module"]
                kind_override = True
            else:
                kind_override = False
            # Two kinds of dispatch name, counted apart: `exec<Function>` is a native the script
            # declares by index, `Native_<index>` is a registered slot with no declarer at all.
            if name.startswith("exec") and not module:
                kind = "gnatives_declared"
            elif NATIVE_SLOT.match(name):
                kind = "gnatives_slot"
            else:
                kind = "other"
            rows.append({"address": row["address"], "name": name, "size": int(row["size"]),
                         "module": module, "unknown": unknown, "kind": kind,
                         "override": kind_override})

    per_module = defaultdict(lambda: {"functions": 0, "bytes": 0, "named": 0})
    for r in rows:
        if r["module"]:
            key = r["module"]
        elif r["unknown"]:
            key = "(unnamed)"
        elif r["kind"] == "gnatives_declared":
            key = "(dispatch: declared)"
        elif r["kind"] == "gnatives_slot":
            key = "(dispatch: slot only)"
        else:
            key = "(other named)"
        d = per_module[key]
        d["functions"] += 1
        d["bytes"] += r["size"]
        if not r["unknown"]:
            d["named"] += 1

    sizes = sorted(r["size"] for r in rows)
    total = sum(sizes)
    median = sizes[len(sizes) // 2] if sizes else 0
    assert_named = sum(1 for r in rows if r["module"] and not r["override"])
    override_named = sum(1 for r in rows if r["override"])
    gnative_named = sum(1 for r in rows if r["kind"] == "gnatives_declared")
    gnative_slot = sum(1 for r in rows if r["kind"] == "gnatives_slot")
    other_named = sum(1 for r in rows if not r["unknown"] and not r["module"]
                      and r["kind"] == "other")

    os.makedirs(args.out, exist_ok=True)
    with open(os.path.join(args.out, "xbe_functions_by_module.csv"), "w", newline="",
              encoding="utf-8") as fh:
        w = csv.writer(fh)
        w.writerow(["module", "functions", "named_from_asserts", "bytes", "mean_size"])
        for module, d in sorted(per_module.items(), key=lambda kv: -kv[1]["functions"]):
            w.writerow([module, d["functions"], d["named"], d["bytes"],
                        round(d["bytes"] / d["functions"], 1)])

    lines = ["# Native side: first Ghidra pass", "",
             "Generated by `tools/native-summary.py` from `symbols/xbox_functions.csv` (Ghidra 12.2,",
             "x86:LE:32, XBE sections carved at their real virtual addresses, base `0x10000`).", "",
             f"- {len(rows):,} functions discovered, {total:,} bytes of code, median function "
             f"{median} bytes",
             f"- {assert_named + override_named:,} functions attributed to a module "
             f"({assert_named:,} by the assert string they reference, {override_named:,} by an evidence "
             f"override — {assert_named / len(rows):.1%} of the binary by assert); {gnative_named:,} are "
             f"named from the runtime native dispatch table (`GNatives`, PLAN 4.4) and {gnative_slot:,} "
             f"are dispatch slots no shipped package declares; {other_named:,} carry a name from Ghidra's "
             f"own analysis (thunks, runtime helpers), the rest are `FUN_*`", "",
             "## Functions by module", "",
             "| module | functions | named | bytes | mean size |", "|---|---|---|---|---|"]
    for module, d in sorted(per_module.items(), key=lambda kv: -kv[1]["functions"]):
        lines.append(f"| `{module}` | {d['functions']:,} | {d['named']:,} | {d['bytes']:,} | "
                     f"{d['bytes'] / d['functions']:.1f} |")
    lines += ["", "## What this does and does not say", "",
              "The module column is derived from the *assert site*, so it attributes a function to the",
              "module whose source file asserts inside it — exact for functions that assert, silent for",
              "those that do not. A function named `Engine_UnObjBas` is therefore an Engine function",
              "that contains an assert from `UnObjBas.cpp`, not necessarily a function *of* that file.",
              "",
              "The `GNatives` rows are a different kind of evidence. `exec<Function>` is the name the",
              "script packages themselves give dispatch slot N, and the address comes from the table read",
              "out of the running build (`inventory/gnatives_slots.csv`), so the pair is as strong as a",
              "native declaration. `Native_<index>` records only that a slot is registered and nothing",
              "declares it: 83 of those are engine-internal execs that no script can reach. An earlier",
              "pass produced 270 `exec*` and 721 `Native_*` names from a pointer array that turned out to",
              "be the CRT initialiser list; those rows are gone and were rebuilt from the runtime table.", "",
              "Everything else is bounded by the 154 translation units that assert at all; the remaining",
              "functions need signature matching (CRT/XAPI/D3D8 libraries) and manual work. `FUN_*` names",
              "are Ghidra's, kept deliberately: an honest unknown beats a guessed name.", "",
              "Assert sites are not the only seed: an XBE has code that nothing calls directly — a script",
              "body is entered through `UFunction::Func`, a native through `GNatives`, a method through a",
              "vtable — so the analyser leaves whole regions un-analysed. `tools/ghidra/SeedGaps.java`",
              "creates a function at the nearest `0xCC`-delimited entry before each assert site that has",
              "none, keeps it only when the assert lands inside the body it produced, and deletes the",
              "candidates that do not. It is what found the VM's own routines (`docs/NATIVE_VM.md`).", "",
              "## Next", "",
              "1. `ProcessEvent`: the caller that builds an `FFrame` and invokes `UFunction::Func` through",
              "   `+0x90`. There is no call edge to follow, so it has to be identified by its own shape",
              "   (`docs/UNKNOWNS.md` U8).",
              "2. The rest of `UObject`/`UStruct`/`FFrame`, and the property/`GPropPointers` tables, now that",
              "   `ProcessInternal` shows how each field is reached.",
              "3. A second `GNatives` dump after a mission loads, for the classes the front end never",
              "   touches (`docs/UNKNOWNS.md` U7).",
              "4. Split the project per module using these attribution counts as the work breakdown (4.5).",
              "5. Signature libraries for the CRT/XAPI/D3D8 majority (4.2) are blocked on data this",
              "   repository may not carry (`docs/UNKNOWNS.md` U9); a locally supplied database is the",
              "   unblock.", ""]
    with open(os.path.join("docs", "NATIVE.md"), "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines))
    print(f"{len(rows)} functions, {assert_named} assert-attributed, {override_named} override-attributed, "
          f"{gnative_named} dispatch-named, {gnative_slot} slot-only, "
          f"{other_named} other named -> docs/NATIVE.md")


if __name__ == "__main__":
    main()
