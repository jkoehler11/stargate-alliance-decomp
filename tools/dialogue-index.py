#!/usr/bin/env python3
"""Index the recorded dialogue by mission, scene and speaker.

`Speech/<Folder>_Final/<mission>_<scene>_<line>_<speaker>.wav` is a naming convention, and it is
metadata the project can publish: the index says how many scenes and which characters each mission
was recorded for, without reproducing a second of audio.

That matters for cut content: dialogue recorded for a mission with no shipped map is content that
was written and performed but not playable in this build.

Usage: dialogue-index.py DUMP_ROOT [-o inventory]
"""
import argparse
import csv
import os
import re
import sys
from collections import Counter, defaultdict

NAME = re.compile(r"^(m\d+[a-z]?)_(\d+)_([a-z])(?:_([a-z0-9]+))?\.wav$", re.IGNORECASE)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("dump_root")
    ap.add_argument("-o", "--out", default="inventory")
    args = ap.parse_args()
    game = os.path.join(args.dump_root, "Stargate_SG-1_-_The_Alliance-2005-12-15")
    root = os.path.join(game if os.path.isdir(game) else args.dump_root, "Speech")
    if not os.path.isdir(root):
        sys.exit(f"no Speech/ directory under {args.dump_root}")

    rows = []
    unmatched = 0
    for dirpath, _dirs, files in os.walk(root):
        folder = os.path.basename(dirpath)
        for name in sorted(files):
            if not name.lower().endswith(".wav"):
                continue
            m = NAME.match(name)
            path = os.path.join(dirpath, name)
            size = os.path.getsize(path)
            if not m:
                unmatched += 1
                rows.append({"folder": folder, "file": name, "mission": "", "scene": "",
                             "line": "", "speaker": "", "bytes": size})
                continue
            rows.append({"folder": folder, "file": name, "mission": m.group(1).lower(),
                         "scene": int(m.group(2)), "line": m.group(3).lower(),
                         "speaker": (m.group(4) or "").lower(), "bytes": size})

    os.makedirs(args.out, exist_ok=True)
    with open(os.path.join(args.out, "speech_index.csv"), "w", newline="", encoding="utf-8") as fh:
        w = csv.DictWriter(fh, fieldnames=["folder", "file", "mission", "scene", "line", "speaker",
                                           "bytes"])
        w.writeheader()
        w.writerows(rows)

    per_mission = defaultdict(lambda: {"lines": 0, "scenes": set(), "speakers": Counter(), "bytes": 0})
    for r in rows:
        if not r["mission"]:
            continue
        d = per_mission[r["mission"]]
        d["lines"] += 1
        d["scenes"].add(r["scene"])
        d["speakers"][r["speaker"] or "?"] += 1
        d["bytes"] += r["bytes"]

    missions = sorted(per_mission, key=lambda m: (len(m), m))
    with open(os.path.join(args.out, "dialogue_by_mission.csv"), "w", newline="", encoding="utf-8") as fh:
        w = csv.writer(fh)
        w.writerow(["mission", "lines", "scenes", "speakers", "bytes"])
        for m in missions:
            d = per_mission[m]
            w.writerow([m, d["lines"], len(d["scenes"]), len(d["speakers"]), d["bytes"]])

    # Which dialogue missions have no map of the same id in this build?
    maps_dir = os.path.join(game if os.path.isdir(game) else args.dump_root, "Maps")
    map_ids = {os.path.splitext(f)[0].lower() for f in os.listdir(maps_dir)} if os.path.isdir(maps_dir) else set()

    def has_map(mission):
        return any(mid.startswith(mission) for mid in map_ids)

    speakers = Counter()
    for d in per_mission.values():
        speakers.update(d["speakers"])

    lines = ["# Dialogue index", "",
             "Generated by `tools/dialogue-index.py` from the `Speech/` WAV names. Filenames follow",
             "`<mission>_<scene>_<line>_<speaker>.wav`; this report publishes counts and character",
             "names, never audio.", "",
             f"- {len(rows):,} WAV files, {sum(r['bytes'] for r in rows) / 2**20:.0f} MiB",
             f"- {len([r for r in rows if r['mission']]):,} follow the mission naming convention, "
             f"{unmatched:,} do not (menu/system voice, handled separately)",
             f"- {len(missions)} mission ids recorded, {len(speakers)} speakers", "",
             "## By mission", "", "| mission | lines | scenes | speakers | map of that id ships |",
             "|---|---|---|---|---|"]
    for m in missions:
        d = per_mission[m]
        lines.append(f"| `{m}` | {d['lines']} | {len(d['scenes'])} | {len(d['speakers'])} | "
                     f"{'yes' if has_map(m) else '**no**'} |")
    lines += ["", "## Speakers", "", "| speaker | lines |", "|---|---|"]
    for speaker, count in speakers.most_common():
        lines.append(f"| `{speaker}` | {count} |")
    no_map = [m for m in missions if not has_map(m)]
    if no_map:
        lines += ["", "## Recorded but not playable in this build", "",
                  f"{len(no_map)} recorded mission ids have no map of the same id in `Maps/`: "
                  + ", ".join(f"`{m}`" for m in no_map) + ".", "",
                  "Weapons, levels and dialogue were produced for a longer campaign than this",
                  "prototype ships — consistent with the 37-chapter `ChapterList.ini` naming maps",
                  "(`m01a`, `m12ax`, …) that are absent (see [CONTENT_CENSUS.md](CONTENT_CENSUS.md)).",
                  "Promoting this from a lead to a claim needs the scene-to-quest mapping in the maps",
                  "or the `.sgs` checkpoints (PLAN 5.4).", ""]
    with open(os.path.join("docs", "DIALOGUE.md"), "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines))
    print(f"{len(rows)} WAVs, {len(missions)} missions, {len(speakers)} speakers, "
          f"{len(no_map)} recorded missions without a map -> docs/DIALOGUE.md")


if __name__ == "__main__":
    main()
